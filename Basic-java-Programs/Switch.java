public class Switch {
    public static void main(String[] args) {
        int x = 10;
        switch(x){
            case 3:
            System.out.println("3 come");
            break;
            case 1:
            System.out.println("1 come");
            break;
            default:
            System.out.println("default");
            break;
        }
    }
}
