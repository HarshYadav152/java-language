public class Literals {
    public static void main(String[] args) {
        // literals --> constant value which can be assigned to the variable
        byte age = 18; // integral literal int and short, byte automatically known its literals
        long num = 293872435436545345L; // we have to specify long literals
        char var = 'h';
        float f1 = 0.2f; // we have to tell which type of literal it is
        // by default, it is double literal
        double vari = 879.9;
        System.out.print(num); // print() never ends with new line

        String harsh = "Yadav";
        System.out.println(harsh); // print() ends with new line
    }
}
