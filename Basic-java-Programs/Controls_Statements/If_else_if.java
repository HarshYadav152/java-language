package Controls_Statements;

public class If_else_if {
    public static void main(String[] args) {
        String name = "Harsh";
        if(name == "Harsh"){
            System.out.println("Name is Harsh");
        }
        else if(name == "Harish"){
            System.out.println("Name is Harish");
        }
        else{
            System.out.println("Name is wrong");
        }
    }
}
